"""Export the numbers behind the paper figures; LaTeX (TikZ/pgfplots) draws them in the document's own font.

Writes to paper/manuscript/figures/:
  fig_numbers.tex           \\newcommand macros: flow-diagram counts and the no-hint control rates
  fig2_<model>_<lang>.csv   arm (a) sycophancy by hint style: x, y (%), eplus, eminus (Wilson 95% CI)
The drawings themselves are fig1_flow.tex and fig2_sycophancy.tex in the same folder (hand-written, no numbers).
Usage: .venv/bin/python scripts/14_figures.py   (rerun after new data, then rebuild the PDF)
"""
import importlib
import pathlib
import sys

import pandas as pd
from statsmodels.stats.proportion import proportion_confint

sys.path.insert(0, str(pathlib.Path(__file__).parent))
score = importlib.import_module("08_score_baseline")
hints = importlib.import_module("11_analyze_hints")
stats = importlib.import_module("12_stats")
OUT = pathlib.Path("paper/manuscript/figures")
OUT.mkdir(parents=True, exist_ok=True)
# model -> macro-safe slug (letters only)
SLUG = {"claude-opus-5-5": "opus", "gpt-6-astra": "astra", "gemini-3.8-flash-high": "gemini",
        "claude-sonnet-5-5": "sonnet", "gpt-5.6-sol": "sol", "gpt-5.6-luna": "luna",
        "gpt-6.1-sol": "solsix", "gpt-6-luna": "lunasix"}
STYLES = ["wrong-overconfidence", "wrong-recency", "wrong-consensus"]


def fmt(n):
    return f"{n:,}"


def numbers():
    db = pd.read_csv("data/ptbxl/ptbxl_database.csv")
    elig = (db.validated_by_human & db.baseline_drift.isna() & db.static_noise.isna()
            & db.burst_noise.isna() & db.electrodes_problems.isna()).sum()
    cases = pd.read_csv("data/cases/candidates.csv")
    base = pd.concat([score.score(r).assign(run=r) for r in "123"])
    ok = (base.groupby(["model", "case_id"]).correct.sum() == 3).groupby("model").sum()
    ctrl = stats.no_hint_control()
    m = {"nECGs": fmt(len(db)), "nPatients": fmt(db.patient_id.nunique()), "nEligible": fmt(int(elig)),
         "nCases": fmt(len(cases)), "nAcute": fmt((cases.group == "acute_mi").sum()),
         "nOld": fmt((cases.group == "old_mi").sum()), "nBaseline": fmt(len(base))}
    for model, slug in SLUG.items():
        m[f"ok{slug}"] = str(int(ok.get(model, 0)))
        c = ctrl[ctrl.model == model]
        m[f"ctrl{slug}"] = f"{c.hits_target.mean() * 100:.1f}" if len(c) else "nan"
    (OUT / "fig_numbers.tex").write_text(
        "% generated by scripts/14_figures.py -- do not edit\n" +
        "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in m.items()))


def fig2_data():
    w = hints.load("a")
    w = w[w.wrong_hint]
    for model, slug in SLUG.items():
        for lang in ("en", "th"):
            rows = []
            for i, st in enumerate(STYLES):
                s = w[(w.model == model) & (w.condition == st) & (w.lang == lang)].sycophantic
                if not len(s):
                    continue
                k, n = int(s.sum()), len(s)
                lo, hi = proportion_confint(k, n, method="wilson")
                rows.append({"x": i + (-0.14 if lang == "en" else 0.14), "y": 100 * k / n,
                             "eplus": 100 * (hi - k / n), "eminus": 100 * (k / n - lo), "n": n})
            pd.DataFrame(rows, columns=["x", "y", "eplus", "eminus", "n"]).round(2).to_csv(
                OUT / f"fig2_{slug}_{lang}.csv", index=False)


if __name__ == "__main__":
    numbers()
    fig2_data()
    print("wrote", *sorted(p.name for p in OUT.glob("fig*")))
